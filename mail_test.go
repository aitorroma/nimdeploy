func TestEmailConfigValidation(t *testing.T) {
	tmpl := filepath.Join(t.TempDir(), "t.html")
	_ = os.WriteFile(tmpl, []byte("{{ .Output.X }}"), 0o600)
	bad := filepath.Join(t.TempDir(), "bad.html")
	_ = os.WriteFile(bad, []byte("{{ .Output.X "), 0o600)
	base := "[logging]\ndirectory = \"/tmp/x\"\n"
	smtp := "[smtp]\nhost = \"smtp.example.com\"\nfrom = \"a@example.com\"\n"
	dep := "[deploy.s]\npath = \"/hooks/s\"\nrepository = \"a/b\"\nsecret_env = \"S\"\ncommand = \"/bin/true\"\n[deploy.s.email]\nsubject = \"x\"\nto = [\"b@example.com\"]\n"
	cases := map[string]string{
		dep + "template = \"" + tmpl + "\"\n":                                       "needs an [smtp] section",
		smtp + dep + "template = \"rel.html\"\n":                                    "absolute path",
		smtp + dep + "template = \"" + bad + "\"\n":                                 "template:",
		smtp + dep + "template = \"" + tmpl + "\"\non = \"sometimes\"\n":            "on must be",
		smtp + dep + "template = \"" + tmpl + "\"\nsecrets = [\"lower\"]\n":         "UPPER_CASE",
		"[smtp]\nhost = \"smtp.example.com\"\nfrom = \"not an address\"\n":          "smtp: from",
		"[smtp]\nhost = \"smtp.example.com\"\nfrom = \"a@b.c\"\ntls = \"none\"\n":   "only allowed for a local relay",
		"[smtp]\nhost = \"smtp.example.com\"\nfrom = \"a@b.c\"\nuser_env = \"U\"\n": "go together",
		"[pwpush]\nurl = \"http://pw.example.com\"\n":                               "must be https",
		"[pwpush]\nexpire_after_duration = 40\n":                                    "index 0-17",
	}
	for extra, want := range cases {
		path := filepath.Join(t.TempDir(), "c.toml")
		content := base + extra
		if !strings.Contains(extra, "[deploy.") {
			content += "[deploy.z]\npath = \"/hooks/z\"\nrepository = \"a/b\"\nsecret_env = \"S\"\ncommand = \"/bin/true\"\n"
		}
		_ = os.WriteFile(path, []byte(content), 0o600)
		if _, err := LoadConfig(path); err == nil || !strings.Contains(err.Error(), want) {
			t.Errorf("%q: got %v, want %q", extra, err, want)
		}
	}
	// Defaults: STARTTLS on 587, 465 means TLS.
	path := filepath.Join(t.TempDir(), "c.toml")
	_ = os.WriteFile(path, []byte(base+"[smtp]\nhost = \"smtp.example.com\"\nport = 465\nfrom = \"a@b.c\"\n"+dep+"template = \""+tmpl+"\"\n"), 0o600)
	cfg, err := LoadConfig(path)
	if err != nil {
		t.Fatal(err)
	}
	if cfg.SMTP.TLS != "tls" || cfg.PwPush.URL != defaultPwPushURL || cfg.PwPush.ExpireAfterViews != 3 || cfg.Deploy["s"].Email.On != "success" {
		t.Fatalf("defaults %+v %+v", cfg.SMTP, cfg.PwPush)
	}
}

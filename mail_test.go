// fakeSMTP is a minimal SMTP server (no TLS, no auth) that records messages.
type fakeSMTP struct {
	ln       net.Listener
	mu       sync.Mutex
	msgs     []smtpMsg
	rejectTo string
}

type smtpMsg struct {
	from string
	rcpt []string
	data string
}

func newFakeSMTP(t *testing.T) *fakeSMTP {
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	f := &fakeSMTP{ln: ln}
	go func() {
		for {
			c, err := ln.Accept()
			if err != nil {
				return
			}
			go f.serve(c)
		}
	}()
	t.Cleanup(func() { ln.Close() })
	return f
}

func (f *fakeSMTP) port() int { return f.ln.Addr().(*net.TCPAddr).Port }

func (f *fakeSMTP) serve(c net.Conn) {
	defer c.Close()
	r := bufio.NewReader(c)
	say := func(s string) { _, _ = io.WriteString(c, s+"\r\n") }
	say("220 fake ESMTP")
	var m smtpMsg
	for {
		line, err := r.ReadString('\n')
		if err != nil {
			return
		}
		cmd := strings.ToUpper(strings.TrimSpace(line))
		switch {
		case strings.HasPrefix(cmd, "EHLO"), strings.HasPrefix(cmd, "HELO"):
			say("250 fake")
		case strings.HasPrefix(cmd, "MAIL FROM:"):
			m = smtpMsg{from: strings.Trim(strings.TrimSpace(line)[10:], "<>")}
			say("250 OK")
		case strings.HasPrefix(cmd, "RCPT TO:"):
			addr := strings.Trim(strings.TrimSpace(line)[8:], "<>")
			f.mu.Lock()
			reject := f.rejectTo != "" && addr == f.rejectTo
			f.mu.Unlock()
			if reject {
				say("550 no such user")
				continue
			}
			m.rcpt = append(m.rcpt, addr)
			say("250 OK")
		case cmd == "DATA":
			say("354 go ahead")
			var b strings.Builder
			for {
				l, err := r.ReadString('\n')
				if err != nil {
					return
				}
				if l == ".\r\n" {
					break
				}
				b.WriteString(l)
			}
			m.data = b.String()
			f.mu.Lock()
			f.msgs = append(f.msgs, m)
			f.mu.Unlock()
			say("250 queued")
		case cmd == "QUIT":
			say("221 bye")
			return
		default:
			say("250 OK")
		}
	}
}

func (f *fakeSMTP) messages() []smtpMsg {
	f.mu.Lock()
	defer f.mu.Unlock()
	return append([]smtpMsg(nil), f.msgs...)
}

// fakePwPush records pushes and answers like an open source instance.
type fakePwPush struct {
	mu     sync.Mutex
	pushes []map[string]any
	auth   []string
}

func (p *fakePwPush) serve(t *testing.T) *httptest.Server {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch {
		case r.Method == http.MethodGet && r.URL.Path == "/api/v2/version":
			_, _ = w.Write([]byte(`{"application_version":"2.14.1","api_version":"2.1","edition":"oss","features":{"anonymous_access":true}}`))
		case r.Method == http.MethodPost && r.URL.Path == "/api/v2/pushes":
			var body struct {
				Push map[string]any `json:"push"`
			}
			_ = json.NewDecoder(r.Body).Decode(&body)
			p.mu.Lock()
			p.pushes = append(p.pushes, body.Push)
			p.auth = append(p.auth, r.Header.Get("Authorization"))
			n := len(p.pushes)
			p.mu.Unlock()
			w.WriteHeader(201)
			_, _ = w.Write([]byte(`{"url_token":"tok` + strconv.Itoa(n) + `","html_url":"https://pw.example.com/p/tok` + strconv.Itoa(n) + `/r"}`))
		default:
			http.NotFound(w, r)
		}
	}))
	t.Cleanup(srv.Close)
	return srv
}

